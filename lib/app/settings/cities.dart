class City {
  const City(this.zh, this.en, this.longitude, {String? hans, this.country = ''}) : _hans = hans;
  final String zh, en;
  final double longitude;
  final String? _hans;

  /// 國家或地區（英文），搜尋時一併比對。
  final String country;

  String get hans => _hans ?? zh;

  String name(String langCode) =>
      langCode == 'zh-Hans' || langCode == 'zh_Hans' ? hans : (langCode.startsWith('zh') ? zh : en);

  bool matches(String q) {
    final s = q.trim().toLowerCase();
    if (s.isEmpty) return true;
    return zh.contains(s) || hans.contains(s) || en.toLowerCase().contains(s) || country.toLowerCase().contains(s);
  }
}

